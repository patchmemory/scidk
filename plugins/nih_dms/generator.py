def render_plan(facts: GraphFacts, generated_at: Optional[str] = None) -> str:
    """Render the draft DMS plan as markdown.

    Args:
        facts: Collected by
            :func:`plugins.nih_dms.graph_facts.collect_facts`.
        generated_at: Timestamp for the provenance line. Defaults to now, in UTC;
            pass one to make output reproducible in a test.

    Returns:
        A markdown document. Always non-empty, and never a static template: with
        no facts to report it says so, section by section, rather than filling in
        plausible prose.
    """
    stamp = generated_at or datetime.now(tz=timezone.utc).strftime('%Y-%m-%d %H:%M UTC')

    lines: List[str] = []
    lines += _preamble(facts, stamp)
    lines += _data_types_section(facts)
    lines += _standards_section(facts)
    lines += _preservation_section(facts)
    lines += _access_section(facts)
    lines += _footer(facts)

    return _tidy(lines)


def _tidy(lines: Iterable[str]) -> str:
    """Join lines, collapsing runs of blank lines so the markdown renders cleanly."""
    out: List[str] = []
    for line in lines:
        if not line.strip() and out and not out[-1].strip():
            continue
        out.append(line.rstrip())
    return '\n'.join(out).strip() + '\n'
